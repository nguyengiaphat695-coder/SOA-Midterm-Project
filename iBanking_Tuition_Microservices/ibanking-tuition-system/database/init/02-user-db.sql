CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE TABLE users (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    username VARCHAR(50) NOT NULL UNIQUE,
    full_name VARCHAR(100) NOT NULL,
    phone VARCHAR(20) NOT NULL UNIQUE,
    email VARCHAR(150) NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE accounts (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id UUID NOT NULL REFERENCES users(id),
    account_number VARCHAR(30) NOT NULL UNIQUE,
    balance NUMERIC(18,0) NOT NULL DEFAULT 0 CHECK (balance >= 0),
    is_default BOOLEAN NOT NULL DEFAULT TRUE,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX one_default_account_per_user ON accounts(user_id) WHERE is_default;
CREATE INDEX idx_accounts_user_id ON accounts(user_id);

-- Debit ledger: idempotent by PAYMENT transaction ID. Never debit one tx twice.
CREATE TABLE account_debits (
    transaction_id UUID PRIMARY KEY,
    account_id UUID NOT NULL REFERENCES accounts(id),
    payer_id UUID NOT NULL REFERENCES users(id),
    amount NUMERIC(18,0) NOT NULL CHECK (amount > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

